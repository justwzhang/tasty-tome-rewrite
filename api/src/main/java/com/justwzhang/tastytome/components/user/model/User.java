package com.justwzhang.tastytome.components.user.model;


public class User {
    Long userId; 
    String firstName; 
    String lastName; 
    String email;

    public Long getUserId() {
        return userId;
    }

    public String getFirstName() {
        return firstName;
    }

    public String getLastName() {
        return lastName;
    }

    public String getEmail() {
        return email;
    }
}